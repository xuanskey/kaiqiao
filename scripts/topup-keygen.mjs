// Never prints key material. Private JWK is created exclusively OUTSIDE the repository.
import { generateKeyPairSync } from 'node:crypto';
import { mkdir, writeFile, chmod, lstat, realpath, access } from 'node:fs/promises';
import path from 'node:path';
const dir='/workspace/kaiqiao-topup-issuer';
await mkdir(dir,{recursive:true,mode:0o700});
if((await lstat(dir)).isSymbolicLink() || await realpath(dir)!==dir)throw Error('Issuer directory must be a real external directory');
if(dir.startsWith(await realpath('.')+path.sep))throw Error('Issuer directory must be outside repository');
await chmod(dir,0o700);
const target=path.join(dir,'private-key.jwk');
try{await access(target);throw Error('Private key already exists; refusing to overwrite');}catch(e){if(e.code!=='ENOENT')throw e;}
const {privateKey,publicKey}=generateKeyPairSync('ec',{namedCurve:'prime256v1'});
await writeFile(target,JSON.stringify(privateKey.export({format:'jwk'})),{flag:'wx',mode:0o600});
const {kty,crv,x,y}=publicKey.export({format:'jwk'});
await writeFile('site/www.yanghat.cn/topup-config.js',`// Public verification key only. Generated explicitly, never regenerated by release.\nexport default ${JSON.stringify({publicKeyJwk:{kty,crv,x,y}},null,2)};\n`);
console.log('Created external private key (0600) and public verification config');
